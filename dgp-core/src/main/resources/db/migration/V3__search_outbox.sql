-- 第四期：检索 Outbox（写路径落库，dgp-search 异步消费）

CREATE TABLE IF NOT EXISTS sys_search_outbox (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id BIGINT,
    entity_type VARCHAR(32) NOT NULL,
    entity_id VARCHAR(64) NOT NULL,
    op VARCHAR(16) NOT NULL,
    create_time TIMESTAMP,
    processed_at TIMESTAMP
);

CREATE INDEX IF NOT EXISTS idx_search_outbox_pending ON sys_search_outbox(processed_at, id);
