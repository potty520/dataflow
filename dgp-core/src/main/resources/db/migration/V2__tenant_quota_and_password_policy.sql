-- 第二期：租户配额 + 强制改密字段（Flyway 只执行一次，勿加 IF NOT EXISTS 以兼容 MySQL）

CREATE TABLE IF NOT EXISTS sys_tenant_quota (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id BIGINT NOT NULL,
    rpm_limit INT DEFAULT 600,
    daily_api_limit INT DEFAULT 100000,
    max_concurrent_jobs INT DEFAULT 20,
    max_storage_mb INT DEFAULT 10240,
    update_time TIMESTAMP
);

CREATE UNIQUE INDEX IF NOT EXISTS uk_tenant_quota ON sys_tenant_quota(tenant_id);

ALTER TABLE sys_user ADD COLUMN must_change_password INT DEFAULT 0;
ALTER TABLE sys_user ADD COLUMN password_changed_at TIMESTAMP;
