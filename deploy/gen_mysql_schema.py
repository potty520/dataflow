#!/usr/bin/env python3
"""把 H2/PostgreSQL 版 schema.sql 转换为 MySQL 8 方言 schema-mysql.sql。

转换规则：
  1. BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY  ->  BIGINT NOT NULL AUTO_INCREMENT PRIMARY KEY
  2. 独立的 CREATE [UNIQUE] INDEX ... ON t(cols);          ->  内联到建表语句的 KEY / UNIQUE KEY
     （MySQL 8 不支持 CREATE INDEX IF NOT EXISTS，内联后随 CREATE TABLE IF NOT EXISTS 天然幂等）
  3. TIMESTAMP -> DATETIME（避免 MySQL 的隐式 DEFAULT/ON UPDATE CURRENT_TIMESTAMP 行为）
  4. 追加 ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_general_ci

同时做基本校验：残留 IDENTITY / CREATE INDEX / 行宽超限 都会报错或告警。
"""
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SRC = ROOT / "backend" / "src" / "main" / "resources" / "schema.sql"
DST = ROOT / "backend" / "src" / "main" / "resources" / "schema-mysql.sql"

INDEX_RE = re.compile(
    r"^\s*CREATE\s+(UNIQUE\s+)?INDEX\s+(?:IF\s+NOT\s+EXISTS\s+)?([A-Za-z0-9_]+)\s+ON\s+([A-Za-z0-9_]+)\s*\(([^)]*)\)\s*;\s*$",
    re.IGNORECASE,
)
CREATE_TABLE_RE = re.compile(r"^\s*CREATE TABLE IF NOT EXISTS ([A-Za-z0-9_]+)\s*\(", re.IGNORECASE)


def main():
    text = SRC.read_text(encoding="utf-8")
    lines = text.splitlines()

    indexes = {}   # table -> [(is_unique, name, cols)]
    body = []
    for line in lines:
        m = INDEX_RE.match(line)
        if m:
            unique = bool(m.group(1))
            indexes.setdefault(m.group(3).lower(), []).append((unique, m.group(2), m.group(4).strip()))
            continue
        body.append(line)

    out = []
    current = None
    for line in body:
        m = CREATE_TABLE_RE.match(line)
        if m:
            current = m.group(1).lower()
            out.append(line)
            continue
        stripped = line.strip()
        if current and stripped.startswith(");"):
            keys = indexes.get(current, [])
            if keys:
                # 前一行若是最后一个列定义且没有逗号，补逗号
                for i in range(len(out) - 1, -1, -1):
                    prev = out[i].rstrip()
                    if not prev or prev.lstrip().startswith("--"):
                        continue
                    if not prev.endswith(","):
                        out[i] = prev + ","
                    break
                for n, (unique, name, cols) in enumerate(keys):
                    suffix = "," if n < len(keys) - 1 else ""
                    out.append("    %sKEY %s (%s)%s" % ("UNIQUE " if unique else "", name, cols, suffix))
            out.append(") ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_general_ci;")
            current = None
            continue
        out.append(line)

    sql = "\n".join(out)
    sql = sql.replace(
        "BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY",
        "BIGINT NOT NULL AUTO_INCREMENT PRIMARY KEY",
    )
    sql = re.sub(r"\bTIMESTAMP\b", "DATETIME", sql)

    # 校验
    problems = []
    if "IDENTITY" in sql.upper():
        problems.append("仍有 IDENTITY 残留")
    if re.search(r"CREATE\s+(UNIQUE\s+)?INDEX", sql, re.IGNORECASE):
        problems.append("仍有 CREATE INDEX 残留")
    tables = len(re.findall(r"CREATE TABLE IF NOT EXISTS", sql, re.IGNORECASE))
    if tables == 0:
        problems.append("未解析到建表语句")

    # 粗略行宽检查（utf8mb4 下 VARCHAR(n) 占 4n 字节；MySQL 行上限 65535）
    for block in re.findall(r"CREATE TABLE IF NOT EXISTS (\w+) \((.*?)\n\) ENGINE", sql, re.S):
        name, cols = block
        size = 0
        for line in cols.splitlines():
            cm = re.search(r"VARCHAR\((\d+)\)", line, re.IGNORECASE)
            if cm:
                size += int(cm.group(1)) * 4 + 2
            elif re.search(r"\bTEXT\b", line, re.IGNORECASE):
                size += 12
            elif re.search(r"\b(BIGINT|DATETIME|DOUBLE)\b", line, re.IGNORECASE):
                size += 8
            elif re.search(r"\b(INT|DATE)\b", line, re.IGNORECASE):
                size += 4
            elif re.search(r"DECIMAL\(", line, re.IGNORECASE):
                size += 10
        if size > 65000:
            problems.append("表 %s 估算行宽 %d 字节，接近/超过 MySQL 65535 上限" % (name, size))

    header = (
        "-- 由 deploy/gen_mysql_schema.py 从 schema.sql 自动生成，请勿手工编辑。\n"
        "-- 方言：MySQL 8.0 / InnoDB / utf8mb4；与 schema.sql（H2/PostgreSQL）保持结构一致。\n"
        "-- 生成规则：IDENTITY -> AUTO_INCREMENT；独立索引内联为 KEY；TIMESTAMP -> DATETIME。\n\n"
    )
    DST.write_text(header + sql + "\n", encoding="utf-8")

    print("generated: %s" % DST)
    print("tables=%d, inline-index-groups=%d, bytes=%d" % (tables, len(indexes), len(sql)))
    if problems:
        print("PROBLEMS:")
        for p in problems:
            print("  - " + p)
        sys.exit(1)
    print("checks: OK (no IDENTITY / no CREATE INDEX / row width sane)")


if __name__ == "__main__":
    main()
